#!/usr/bin/env node
/**
 * Regenerates the docs-track section in .gitignore from docs/.tracked.
 * Run via: npm run docs:git-sync
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST_PATH = path.join(ROOT, "docs", ".tracked");
const GITIGNORE_PATH = path.join(ROOT, ".gitignore");

const BEGIN = "# BEGIN docs-track";
const END = "# END docs-track";

/** @param {string} content */
function parseManifest(content) {
  return content
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"));
}

/**
 * Git needs parent directories un-ignored before a nested file.
 * @param {string} relativePath path under docs/
 */
function negationsFor(relativePath) {
  const normalized = relativePath.replace(/\\/g, "/").replace(/^\//, "");
  const parts = normalized.split("/").filter(Boolean);
  const lines = [];

  for (let i = 0; i < parts.length; i++) {
    const segment = parts.slice(0, i + 1).join("/");
    const isLast = i === parts.length - 1;
    lines.push(isLast ? `!/docs/${segment}` : `!/docs/${segment}/`);
  }

  return lines;
}

/** @param {string[]} trackedPaths */
function buildBlock(trackedPaths) {
  const negationSet = new Set(["!/docs/.tracked"]);

  for (const trackedPath of trackedPaths) {
    for (const line of negationsFor(trackedPath)) {
      negationSet.add(line);
    }
  }

  return [
    BEGIN,
    "# Generated by scripts/sync-docs-gitignore.mjs — run: npm run docs:git-sync",
    "/docs/**",
    ...Array.from(negationSet).sort(),
    END,
  ].join("\n");
}

/** @param {string} gitignore */
function replaceBlock(gitignore, block) {
  const pattern = new RegExp(
    `${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`,
  );

  if (!pattern.test(gitignore)) {
    throw new Error(
      `Missing ${BEGIN} / ${END} markers in .gitignore. Add an empty docs-track section first.`,
    );
  }

  return gitignore.replace(pattern, block);
}

function main() {
  const manifest = fs.readFileSync(MANIFEST_PATH, "utf8");
  const trackedPaths = parseManifest(manifest);
  const block = buildBlock(trackedPaths);
  const gitignore = fs.readFileSync(GITIGNORE_PATH, "utf8");
  const next = replaceBlock(gitignore, block);

  if (next !== gitignore) {
    fs.writeFileSync(GITIGNORE_PATH, next.endsWith("\n") ? next : `${next}\n`);
    console.log(
      `Updated .gitignore docs-track section (${trackedPaths.length} tracked doc(s)).`,
    );
  } else {
    console.log(
      `docs-track section already up to date (${trackedPaths.length} tracked doc(s)).`,
    );
  }
}

main();
