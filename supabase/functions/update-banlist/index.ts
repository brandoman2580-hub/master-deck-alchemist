/**
 * Supabase Edge Function: Update Master Duel Banlist using Browserless
 */

import { createClient } from "@supabase/supabase-js";
import { corsHeaders } from "../_shared/cors.ts";
import * as cheerio from "cheerio";

const supabase = createClient(
  Deno.env.get("SUPABASE_URL") ?? "",
  Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") ?? "",
);

type BanStatus = "Forbidden" | "Limited" | "Semi-Limited" | "Unlimited";

interface BanlistRow {
  card_name: string;
  ban_status: BanStatus;
}

function parseBanStatus(src: string): BanStatus {
  src = src.toLowerCase();

  if (src.includes("forbidden")) return "Forbidden";
  if (src.includes("limited-1")) return "Limited";
  if (src.includes("limited-2")) return "Semi-Limited";
  return "Unlimited";
}

function parseBanlist(html: string): BanlistRow[] {
  const entries: BanlistRow[] = [];
  const $ = cheerio.load(html);

  const statusImages = $("img.fl-icon").toArray();

  if (statusImages.length === 0) {
    const allImages = $("img").toArray();

    for (let i = 0; i < allImages.length - 1; i += 2) {
      const statusImg = allImages[i];
      const cardImg = allImages[i + 1];

      const statusSrc = $(statusImg).attr("src") ?? "";
      let cardAlt = ($(cardImg).attr("alt") ?? "").trim();

      if (!cardAlt || cardAlt === "[object Object]") {
        continue;
      }

      const notFoundPrefix = "Card not found (";
      if (cardAlt.startsWith(notFoundPrefix) && cardAlt.endsWith(")")) {
        cardAlt = cardAlt.slice(notFoundPrefix.length, -1).trim();
      }

      const status = parseBanStatus(statusSrc);

      if (cardAlt) {
        entries.push({ card_name: cardAlt, ban_status: status });
      }
    }
  } else {
    statusImages.forEach((statusImg) => {
      const statusSrc = $(statusImg).attr("src") ?? "";

      let cardImg = $(statusImg).next("img.card-img").get(0);

      if (!cardImg) {
        cardImg = $(statusImg).next("img").get(0);
      }

      if (!cardImg) {
        const parent = $(statusImg).parent();
        const cardImgs = parent.find("img.card-img").toArray();
        if (cardImgs.length > 0) {
          cardImg = cardImgs[0];
        }
      }

      if (!cardImg) {
        const allImgs = $("img").toArray();
        const statusIndex = allImgs.indexOf(statusImg);
        if (statusIndex >= 0 && statusIndex < allImgs.length - 1) {
          cardImg = allImgs[statusIndex + 1];
        }
      }

      if (!cardImg) {
        return;
      }

      let cardAlt = ($(cardImg).attr("alt") ?? "").trim();

      if (!cardAlt || cardAlt === "[object Object]") {
        return;
      }

      const notFoundPrefix = "Card not found (";
      if (cardAlt.startsWith(notFoundPrefix) && cardAlt.endsWith(")")) {
        cardAlt = cardAlt.slice(notFoundPrefix.length, -1).trim();
      }

      const status = parseBanStatus(statusSrc);

      if (cardAlt) {
        entries.push({ card_name: cardAlt, ban_status: status });
      }
    });
  }

  return entries;
}

async function upsertBanlistEntries(entries: BanlistRow[]) {
  if (entries.length === 0) return { inserted: 0, updated: 0 };

  const uniqueEntries = new Map<string, BanlistRow>();
  for (const entry of entries) {
    uniqueEntries.set(entry.card_name, entry);
  }
  const deduplicatedEntries = Array.from(uniqueEntries.values());

  const cardNames = deduplicatedEntries.map((e) => e.card_name);
  const { data: existingData, error: fetchError } = await supabase
    .from("master_duel_banlist")
    .select("id, card_name, ban_status")
    .in("card_name", cardNames);

  if (fetchError) {
    if (fetchError.message.includes("does not exist")) {
      throw new Error(
        `Table 'master_duel_banlist' does not exist. Please create it first using:\n` +
          `CREATE TABLE public.master_duel_banlist (\n` +
          `  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n` +
          `  card_name TEXT NULL,\n` +
          `  ban_status TEXT NULL,\n` +
          `  CONSTRAINT master_duel_banlist_pkey PRIMARY KEY (id)\n` +
          `);`,
      );
    }
    throw new Error(`Failed to fetch existing entries: ${fetchError.message}`);
  }

  const existingMap = new Map<
    string,
    { id: number; card_name: string; ban_status: string }
  >();
  if (existingData) {
    for (const row of existingData) {
      existingMap.set(row.card_name, row);
    }
  }

  const upsertPayload: Array<{
    id?: number;
    card_name: string;
    ban_status: string;
  }> = [];

  for (const entry of deduplicatedEntries) {
    const existing = existingMap.get(entry.card_name);
    if (existing) {
      upsertPayload.push({
        id: existing.id,
        card_name: entry.card_name,
        ban_status: entry.ban_status,
      });
    } else {
      upsertPayload.push({
        card_name: entry.card_name,
        ban_status: entry.ban_status,
      });
    }
  }

  const { data, error } = await supabase
    .from("master_duel_banlist")
    .upsert(upsertPayload)
    .select();

  if (error) {
    throw new Error(`Supabase upsert error: ${error.message}`);
  }

  const existingCount = existingMap.size;
  const totalCount = data?.length ?? upsertPayload.length;
  const insertedCount = totalCount - existingCount;
  const updatedCount = existingCount;

  console.log(
    `Upserted ${insertedCount} new entries and updated ${updatedCount} existing entries`,
  );

  return { inserted: insertedCount, updated: updatedCount };
}

async function fetchRenderedHTMLWithBrowserless(url: string): Promise<string> {
  const BROWSERLESS_API_KEY = Deno.env.get("BROWSERLESS_API_KEY");
  if (!BROWSERLESS_API_KEY) {
    throw new Error("Missing BROWSERLESS_API_KEY environment variable");
  }

  const data = {
    url,
    elements: [{ selector: "a.image-wrapper", timeout: 30000 }],
  };

  const response = await fetch(
    `https://production-sfo.browserless.io/scrape?token=${BROWSERLESS_API_KEY}&headless=true`,
    {
      method: "POST",
      headers: {
        "Cache-Control": "no-cache",
        "Content-Type": "application/json",
      },
      body: JSON.stringify(data),
    },
  );

  if (!response.ok) {
    const text = await response.text();
    throw new Error(`Browserless API error: ${response.status} ${text}`);
  }

  const json = await response.json();

  if (!json.data || !json.data[0] || !json.data[0].results) {
    throw new Error("Unexpected Browserless JSON structure");
  }

  const htmlSnippets = json.data[0].results.map((result: any) => result.html);
  const concatenatedHtml = htmlSnippets.join("\n");

  return concatenatedHtml;
}

Deno.serve(async (req: Request) => {
  if (req.method === "OPTIONS") {
    return new Response("ok", { headers: corsHeaders });
  }
  try {
    const banlistUrl =
      Deno.env.get("BANLIST_SOURCE_URL") ??
      "https://www.masterduelmeta.com/forbidden-limited-list";

    const renderedHtml = await fetchRenderedHTMLWithBrowserless(banlistUrl);
    const entries = parseBanlist(renderedHtml);

    if (entries.length === 0) {
      return new Response(
        JSON.stringify({
          status: "error",
          message:
            "No entries found; the page's HTML structure may have changed.",
          details:
            "Ensure Browserless rendering is working or data source URL is correct.",
        }),
        {
          status: 500,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        },
      );
    }

    const { inserted, updated } = await upsertBanlistEntries(entries);

    return new Response(
      JSON.stringify({
        status: "success",
        count: entries.length,
        inserted,
        updated,
        message: `Successfully updated banlist with ${entries.length} entries.`,
        timestamp: new Date().toISOString(),
      }),
      {
        status: 200,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      },
    );
  } catch (error) {
    console.error("Error in update-banlist function:", error);
    return new Response(
      JSON.stringify({
        status: "error",
        message: error instanceof Error ? error.message : String(error),
      }),
      {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      },
    );
  }
});
